def update_en_json():
    """Add all NEW_UI_KEYS to en.json under the 'ui' section."""
    en_file = os.path.join(LOCALES_DIR, 'en.json')
    with open(en_file, 'r', encoding='utf-8') as f:
        data = json.load(f)

    if 'ui' not in data:
        data['ui'] = {}

    added = 0
    for key, value in NEW_UI_KEYS.items():
        if key not in data['ui']:
            data['ui'][key] = value
            added += 1

    with open(en_file, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
        f.write('\n')

    print(f"en.json: added {added} new ui.* keys")


def update_locale_json(locale_code):
    """Add translated keys to a locale file."""
    locale_file = os.path.join(LOCALES_DIR, f'{locale_code}.json')
    if not os.path.exists(locale_file):
        print(f"  Skipping {locale_code}.json — file not found")
        return

    with open(locale_file, 'r', encoding='utf-8') as f:
        data = json.load(f)

    if 'ui' not in data:
        data['ui'] = {}

    translations = TRANSLATIONS.get(locale_code, {})
    added = 0
    for key, en_val in NEW_UI_KEYS.items():
        if key not in data['ui']:
            # Use specific translation if available, else fall back to English
            data['ui'][key] = translations.get(key, en_val)
            added += 1

    with open(locale_file, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
        f.write('\n')

    print(f"  {locale_code}.json: added {added} new ui.* keys")


def main():
    print("=== Step 1: Updating en.json ===")
    update_en_json()

    print("\n=== Step 2: Updating all locale files ===")
    for locale in LOCALES:
        update_locale_json(locale)

    print("\nDone.")


if __name__ == '__main__':
    main()
